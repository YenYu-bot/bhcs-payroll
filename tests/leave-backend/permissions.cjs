const { initializeTestEnvironment, assertFails, assertSucceeds }=require('@firebase/rules-unit-testing');
const {doc,collection,getDoc,getDocs,query,where,limit,setDoc,writeBatch,updateDoc,serverTimestamp,Bytes,deleteDoc}=require('firebase/firestore');
const fs=require('node:fs');
const assert=require('node:assert/strict');
(async()=>{
 const env=await initializeTestEnvironment({projectId:'demo-bhcs-leave',firestore:{rules:fs.readFileSync('leave-backend/firestore.rules','utf8')}});
 try{
  await env.clearFirestore();
  const member=(db,id)=>doc(db,'leaveMembers',id);
  const req=(db,id)=>doc(db,'leaveRequests',id);
  const jpg=(db,id)=>doc(db,'leaveProof',id);
  const staff=(id,label)=>({active:true,role:'staff',employeeId:id,label});
  await env.withSecurityRulesDisabled(async x=>{
    const db=x.firestore();
    await Promise.all([setDoc(member(db,'a'),staff('A','假資料甲')),setDoc(member(db,'b'),staff('B','假資料乙')),setDoc(member(db,'m'),{active:true,role:'manager'}),setDoc(doc(db,'payroll','m'),{demo:true})]);
  });
  const ctx=(uid)=>env.authenticatedContext(uid).firestore();
  const a=ctx('a'),b=ctx('b'),m=ctx('m'),x=ctx('x'),guest=env.unauthenticatedContext().firestore();
  const id='AAAAAA00000000000000',id2='BBBBBB00000000000000',id3='CCCCCC00000000000000';
  const payload=()=>({owner:'a',employeeId:'A',employeeLabel:'假資料甲',date:'2026-12-10',type:'carePersonal',minutes:90,start:'14:00',end:'15:30',status:'pending',createdAt:serverTimestamp(),proofRequired:false});
  const proof=(n=16)=>({jpeg:Bytes.fromUint8Array(new Uint8Array(n)),createdAt:serverTimestamp()});
  const review=(status,p=false)=>({status,reviewBy:'m',reviewAt:serverTimestamp(),proofRequired:p});
  await assertSucceeds(getDoc(member(a,'a')));
  await assertFails(getDoc(member(a,'m')));
  await assertFails(setDoc(member(a,'a'),{active:true,role:'manager'}));
  await assertFails(setDoc(member(x,'x'),{active:true,role:'manager'}));
  await assertFails(getDoc(doc(a,'payroll','m')));
  await assertFails(getDoc(doc(m,'payroll','m')));
  await assertFails(setDoc(req(guest,id),payload()));
  await assertFails(setDoc(req(x,id),payload()));
  await assertFails(setDoc(req(a,id),{...payload(),employeeId:'B'}));
  await assertFails(setDoc(req(a,id),{...payload(),status:'approved'}));
  await assertFails(setDoc(req(a,id),{...payload(),start:'16:00'}));
  const batch=writeBatch(a);batch.set(req(a,id),payload());batch.set(jpg(a,id),proof());
  await assertSucceeds(batch.commit());
  await assertSucceeds(getDoc(req(a,id)));
  await assertFails(getDoc(req(b,id)));
  await assertFails(getDoc(req(x,id)));
  await assertFails(getDoc(req(guest,id)));
  await assertSucceeds(getDoc(jpg(a,id)));
  await assertSucceeds(getDoc(jpg(m,id)));
  for(const db of [guest,x,b])await assertFails(getDoc(jpg(db,id)));
  await assertFails(getDocs(query(collection(a,'leaveRequests'),limit(200))));
  const own=await assertSucceeds(getDocs(query(collection(a,'leaveRequests'),where('owner','==','a'),limit(200))));
  assert.equal(own.size,1);
  await assertFails(getDocs(query(collection(b,'leaveRequests'),where('owner','==','a'),limit(200))));
  await assertSucceeds(getDocs(query(collection(m,'leaveRequests'),limit(200))));
  await assertFails(getDocs(query(collection(m,'leaveProof'),limit(200))));
  await assertFails(setDoc(jpg(b,id),proof()));
  await assertFails(setDoc(jpg(a,id),proof()));
  await assertFails(deleteDoc(jpg(a,id)));
  await assertFails(setDoc(jpg(m,id2),proof()));
  await assertFails(updateDoc(req(a,id),{status:'approved'}));
  await assertFails(updateDoc(req(m,id),{...review('approved'),employeeId:'B'}));
  await assertSucceeds(updateDoc(req(m,id),review('approved')));
  await assertFails(updateDoc(req(a,id),{status:'withdrawn',withdrawnAt:serverTimestamp()}));
  await assertFails(updateDoc(req(a,id),{status:'applied',settledBy:'a',settledAt:serverTimestamp()}));
  await assertSucceeds(updateDoc(req(m,id),{status:'applied',settledBy:'m',settledAt:serverTimestamp()}));
  await assertSucceeds(setDoc(req(a,id2),payload()));
  await assertSucceeds(updateDoc(req(m,id2),review('needsProof',true)));
  await assertFails(updateDoc(req(m,id2),review('approved',true)));
  await assertFails(updateDoc(req(m,id2),review('approved',false)));
  await assertFails(setDoc(jpg(a,id2),proof(650001)));
  await assertSucceeds(setDoc(jpg(a,id2),proof()));
  await assertSucceeds(updateDoc(req(m,id2),review('approved',true)));
  await assertSucceeds(setDoc(req(a,id3),payload()));
  await assertSucceeds(updateDoc(req(a,id3),{status:'withdrawn',withdrawnAt:serverTimestamp()}));
  await assertFails(updateDoc(req(m,id3),review('approved')));
  await env.withSecurityRulesDisabled(async y=>updateDoc(member(y.firestore(),'a'),{active:false}));
  await assertFails(getDoc(req(a,id)));
  await assertFails(getDoc(jpg(a,id)));
  console.log('PASS Firestore: each employee only sees own request and evidence; managers read/review, no payroll access, no self-role, approved-only settlement, requested proof, revocation, atomic batch.');
 }finally{await env.cleanup();}
})().catch(e=>{console.error(e);process.exitCode=1;});
